#!/usr/bin/env python3
"""Run a pgTAP file against the linked hosted Supabase project WITHOUT Docker.

`supabase test db --remote` (CLI 3.1.0) needs Docker for its test runner,
which this project forbids (research R16). `supabase db query --remote`
executes SQL remotely but only prints the LAST statement's result set, so
this wrapper:

1. installs real pgTAP inside the transaction (`create extension pgtap`);
2. grants `authenticated` execute rights so assertions also run after
   `set role authenticated` (RLS tests);
3. rewrites every `select <assertion>(...)` into
   `insert into tap_lines (line) select <assertion>(...)`;
4. appends a final SELECT that prints every buffered TAP line.

The test files stay standard pgTAP and remain runnable with
`supabase test db --remote` wherever Docker exists.

Usage: python scripts/run_remote_pgtap.py supabase/tests/001_schema_test.sql [...]
"""
import io
import os
import re
import subprocess
import sys
import tempfile

CLI = os.path.join(os.environ.get('LOCALAPPDATA', ''), 'supabase-cli',
                   'supabase.exe')

PRELUDE = """\
-- generated by scripts/run_remote_pgtap.py
-- Real pgTAP runs in-transaction; assertion SELECTs are rewritten below to
-- buffer their TAP lines (db query only surfaces the last result set).
create temp table tap_lines (id serial primary key, line text);
grant insert on tap_lines to authenticated;
grant usage, select on sequence tap_lines_id_seq to authenticated;
grant usage on schema extensions to authenticated;
grant execute on all functions in schema extensions to authenticated;
"""

FINALE = """
select line from tap_lines order by id;
"""

ASSERTION_RE = re.compile(
    r'(?m)^select\s+(is|ok|throws_ok|lives_ok|has_table|has_column|has_index|'
    r'col_is|col_type_is|fk_ok|tables_are|columns_are|indexes_are|'
    r'policy_is|database_is|has_type|enum_has_labels|has_role|has_schema|'
    r'has_function|has_trigger|is_empty|results_eq|set_eq|is_superset_of)'
    r'\s*\(')


def transform(sql: str) -> str:
    body = re.sub(r'^\s*begin\s*;\s*$', '', sql, flags=re.M)
    body = re.sub(r'^\s*rollback\s*;\s*$', '', body, flags=re.M)
    body = re.sub(r'select\s+\*\s+from\s+finish\(\)\s*;', '', body)

    def _include(match):
        rel = match.group(1).strip().replace('\\', '/')
        inc = rel if rel.startswith('supabase/') else os.path.join(
            'supabase', 'tests', rel)
        return io.open(inc, encoding='utf-8').read()

    body = re.sub(r'\\i\s+(.+)$', _include, body, flags=re.M)

    # Buffer assertion outputs so they survive to the last result set.
    body = ASSERTION_RE.sub(
        lambda m: 'insert into tap_lines (line) select ' + m.group(1) + '(',
        body)
    return 'begin;\n' + PRELUDE + body + FINALE + 'rollback;\n'


def main(argv):
    if not argv:
        print('usage: run_remote_pgtap.py <test.sql> [...]', file=sys.stderr)
        return 2
    any_failed = False
    for path in argv:
        body = io.open(path, encoding='utf-8').read()
        with tempfile.NamedTemporaryFile(
                'w', encoding='utf-8', suffix='.sql', delete=False) as f:
            f.write(transform(body))
            tmp = f.name
        try:
            proc = subprocess.run(
                [CLI, 'db', 'query', '--remote', '-f', tmp, '--yes'],
                capture_output=True, text=True, timeout=900,
                encoding='utf-8', errors='replace')
            text = (proc.stdout or '') + (proc.stderr or '')
        finally:
            os.unlink(tmp)

        lines = [ln.strip().strip('│').strip() for ln in text.split('\n')]
        tap = [ln for ln in lines if ln.startswith('ok ') or 'not ok' in ln]
        diag = [ln for ln in lines if ln.startswith('#')]
        not_ok = [ln for ln in tap if 'not ok' in ln]
        print('%s: %d passed, %d failed'
              % (os.path.basename(path), len(tap) - len(not_ok), len(not_ok)))
        for ln in not_ok:
            print('  ' + ln)
        for ln in diag:
            print('  ' + ln)
        if not_ok:
            any_failed = True
        if not tap:
            print('  (no tap output — raw output below)')
            print(text[:3000].encode('ascii', 'replace').decode())
    return 1 if any_failed else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
