#!/usr/bin/env python3
"""Run a pgTAP file against the linked hosted Supabase project WITHOUT Docker.

`supabase test db --remote` (CLI 3.1.0) needs Docker for its test runner,
which this project forbids (research R16). `supabase db query --remote`
executes SQL remotely but only prints the LAST statement's result set, so
this wrapper:

1. creates a temp table + pg_temp functions shadowing the pgTAP assertions
   used in this repo (is / has_table / has_column / throws_ok), each
   recording its tap line;
2. appends a final SELECT that prints every recorded line.

The test files themselves stay standard pgTAP and remain runnable with
`supabase test db --remote` wherever Docker exists.

Usage: python scripts/run_remote_pgtap.py supabase/tests/001_schema_test.sql [...]
"""
import io
import os
import subprocess
import sys
import tempfile

CLI = os.path.join(os.environ.get('LOCALAPPDATA', ''), 'supabase-cli',
                   'supabase.exe')

PRELUDE = """\
-- generated by scripts/run_remote_pgtap.py
-- Temporary (pg_temp) FUNCTIONS are not resolved by unqualified calls on
-- the hosted Postgres, so the wrappers live in a real schema created inside
-- this transaction and destroyed by the final rollback.
create schema if not exists tests;
set search_path = tests, public, extensions;
create temp table tap_lines (id serial primary key, line text);

create function tests.is(got anyelement, want anyelement, descr text)
returns text language plpgsql as $fn$
declare r text;
begin
  r := extensions.is(got, want, descr);
  insert into tap_lines (line) values (r);
  return r;
end
$fn$;

create function tests.is(got text, want text, descr text)
returns text language plpgsql as $fn$
declare r text;
begin
  r := extensions.is(got, want, descr);
  insert into tap_lines (line) values (r);
  return r;
end
$fn$;

create function tests.has_table(schema text, tbl text, descr text)
returns text language plpgsql as $fn$
declare r text;
begin
  r := extensions.has_table(schema, tbl, descr)::text;
  insert into tap_lines (line) values (r);
  return r;
end
$fn$;

create function tests.has_column(schema text, tbl text, col text, descr text)
returns text language plpgsql as $fn$
declare r text;
begin
  r := extensions.has_column(schema, tbl, col, descr)::text;
  insert into tap_lines (line) values (r);
  return r;
end
$fn$;

create function tests.throws_ok(query text, msg text)
returns text language plpgsql as $fn$
declare r text;
begin
  r := extensions.throws_ok(query, msg);
  insert into tap_lines (line) values (r);
  return r;
end
$fn$;

create function tests.throws_ok(query text, errcode int)
returns text language plpgsql as $fn$
declare r text;
begin
  r := extensions.throws_ok(query, errcode);
  insert into tap_lines (line) values (r);
  return r;
end
$fn$;

create function tests.ok(got boolean, descr text)
returns text language plpgsql as $fn$
declare r text;
begin
  r := extensions.ok(got, descr);
  insert into tap_lines (line) values (r);
  return r;
end
$fn$;

create function tests.lives_ok(query text, descr text)
returns text language plpgsql as $fn$
declare r text;
begin
  r := extensions.lives_ok(query, descr);
  insert into tap_lines (line) values (r);
  return r;
end
$fn$;
"""

FINALE = "\nselect line from tap_lines order by id;\n"


def main(argv):
    if not argv:
        print('usage: run_remote_pgtap.py <test.sql> [...]', file=sys.stderr)
        return 2
    any_failed = False
    for path in argv:
        body = io.open(path, encoding='utf-8').read()
        # The file's own begin/rollback would abort the temp table too (db
        # query wraps the whole file in one transaction). Strip it and use
        # our own transaction.
        import re
        body = re.sub(r'^\s*begin\s*;\s*$', '', body, flags=re.M)
        body = re.sub(r'^\s*rollback\s*;\s*$', '', body, flags=re.M)
        with tempfile.NamedTemporaryFile(
                'w', encoding='utf-8', suffix='.sql', delete=False) as f:
            f.write('begin;\n' + PRELUDE + body + FINALE + 'rollback;\n')
            tmp = f.name
        try:
            proc = subprocess.run(
                [CLI, 'db', 'query', '--remote', '-f', tmp, '--yes'],
                capture_output=True, text=True, timeout=900,
                encoding='utf-8', errors='replace')
            text = (proc.stdout or '') + (proc.stderr or '')
        finally:
            os.unlink(tmp)

        lines = [ln.strip().strip('│').strip() for ln in text.split('\n')]
        tap = [ln for ln in lines if ln.startswith('ok ') or 'not ok' in ln]
        not_ok = [ln for ln in tap if 'not ok' in ln]
        print('%s: %d passed, %d failed'
              % (os.path.basename(path), len(tap) - len(not_ok), len(not_ok)))
        for ln in not_ok:
            print('  ' + ln)
        if not_ok:
            any_failed = True
        if not tap:
            print('  (no tap output — raw output below)')
            safe = text[:3000].encode('ascii', 'replace').decode()
            print(safe)
    return 1 if any_failed else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
